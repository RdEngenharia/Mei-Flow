/**
 * Busca por palavras soltas: "instalacao solar" acha o mesmo que "solar
 * instalacao". Cada palavra precisa aparecer em algum lugar — descrição,
 * termos do dia a dia ou o próprio código.
 */
export function buscarServicos(consulta: string, limite = 40): ServicoNacional[] {
  const palavras = semAcento(String(consulta || "").trim()).split(/\s+/).filter(Boolean);
  if (!palavras.length) return [];

  const pontuar = (s: ServicoNacional): number => {
    const alvo = semAcento(s.d) + " " + semAcento(s.t || "") + " " + s.c + " " + formatarCodigoServico(s.c);
    if (!palavras.every((p) => alvo.includes(p))) return -1;
    // Quem casa nos termos do dia a dia sobe: é sinal de que o usuário usou a
    // palavra que ele mesmo usaria, e não a da lei.
    const nosTermos = palavras.filter((p) => semAcento(s.t || "").includes(p)).length;
    const comeca = semAcento(s.d).startsWith(palavras[0]) ? 2 : 0;
    return nosTermos * 3 + comeca;
  };

  return SERVICOS_NACIONAIS
    .map((s) => ({ s, p: pontuar(s) }))
    .filter((x) => x.p >= 0)
    .sort((a, b) => b.p - a.p)
    .slice(0, limite)
    .map((x) => x.s);
}

/** Descrição oficial de um código, para mostrar o que foi escolhido. */
export function descricaoDoCodigo(c: string): string {
  const limpo = String(c || "").replace(/\D/g, "");
  return SERVICOS_NACIONAIS.find((s) => s.c === limpo)?.d || "";
}
